"""Writes crates/sp-settings/src/pyuni.rs, the few Unicode tables sp-settings needs to act exactly like CPython. They
cover the whitespace str.split() and str.strip() take off, the digits \\d, float() and int() read, str.isdigit,
str.isprintable for repr(), and the extra characters re's IGNORECASE lets into [A-Za-z0-9_-].

    .venv/bin/python mac/core/tools/settings_unicode_tables.py

Generated from the Python that runs it (its unicodedata version is written into the file).
"""
from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "crates" / "sp-settings" / "src" / "pyuni.rs"


def ranges(pred) -> list[tuple[int, int]]:
    out, start = [], None
    for c in range(0x110001):
        p = c < 0x110000 and pred(c)
        if p and start is None:
            start = c
        if not p and start is not None:
            out.append((start, c - 1))
            start = None
    return out


def table(name: str, rs: list[tuple[int, int]]) -> str:
    rows = ", ".join(f"(0x{a:X}, 0x{b:X})" for a, b in rs)
    return f"pub(crate) const {name}: &[(u32, u32)] = &[{rows}];\n"


def main() -> None:
    space = [c for c in range(0x110000) if chr(c).isspace()]
    zeros = [c for c in range(0x110000) if unicodedata.category(chr(c)) == "Nd" and unicodedata.digit(chr(c)) == 0]
    assert all(unicodedata.digit(chr(z + i)) == i for z in zeros for i in range(10))
    pat = re.compile(r"(?i)[A-Za-z0-9_-]")
    code_extra = [c for c in range(128, 0x110000) if pat.fullmatch(chr(c))]
    s_extra = [c for c in range(128, 0x110000) if re.fullmatch(r"(?i)S", chr(c))]
    p_extra = [c for c in range(128, 0x110000) if re.fullmatch(r"(?i)P", chr(c))]
    l_extra = [c for c in range(128, 0x110000) if re.fullmatch(r"(?i)L", chr(c))]
    text = (
        "// Generated by mac/core/tools/settings_unicode_tables.py from Python "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.\n\n"
        "/// str.isspace(): what str.split() and str.strip() take off.\n"
        f"pub(crate) const SPACE: &[u32] = &[{', '.join(f'0x{c:X}' for c in space)}];\n"
        "/// The zero of each run of ten Unicode decimal digits (category Nd): \\d, float(), int().\n"
        f"pub(crate) const ND_ZEROS: &[u32] = &[{', '.join(f'0x{c:X}' for c in zeros)}];\n"
        "/// str.isdigit().\n"
        + table("ISDIGIT", ranges(lambda c: chr(c).isdigit()))
        + "/// Not str.isprintable(): repr() escapes these.\n"
        + table("NONPRINTABLE", ranges(lambda c: not chr(c).isprintable()))
        + "/// Characters beyond ASCII that (?i)[A-Za-z0-9_-] matches, and (?i)S, (?i)P, (?i)L.\n"
        f"pub(crate) const CODE_EXTRA: &[u32] = &[{', '.join(f'0x{c:X}' for c in code_extra)}];\n"
        f"pub(crate) const S_EXTRA: &[u32] = &[{', '.join(f'0x{c:X}' for c in s_extra)}];\n"
        f"pub(crate) const P_EXTRA: &[u32] = &[{', '.join(f'0x{c:X}' for c in p_extra)}];\n"
        f"pub(crate) const L_EXTRA: &[u32] = &[{', '.join(f'0x{c:X}' for c in l_extra)}];\n"
    )
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
