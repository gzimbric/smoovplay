"""Writes crates/sp-settings/src/generated.rs from the Python reference: every setting in framegen/settings.py's SPECS,
the look node types (framegen/looks.py TYPES_LIST) and the built-in looks (looks.BUILTIN, as normalize() leaves them).
Run it after a setting, a node type or a built-in look changes in the Python:

    .venv/bin/python mac/core/tools/settings_codegen.py

so the Rust core never keeps a hand-made copy that can drift (the parity tests check the result).
"""
from __future__ import annotations

import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parents[1] / "crates" / "sp-settings" / "src" / "generated.rs"


def rust_str(s: str) -> str:
    out = ['"']
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif " " <= c <= "~":
            out.append(c)
        else:
            out.append(f"\\u{{{ord(c):x}}}")
    out.append('"')
    return "".join(out)


def rust_float(x: float) -> str:
    r = repr(float(x))
    return r if ("." in r or "e" in r) else r + ".0"


def choice(v) -> str:
    if isinstance(v, bool):
        return f"B({'true' if v else 'false'})"
    if isinstance(v, int):
        return f"I({v})"
    if isinstance(v, float):
        return f"F({rust_float(v)})"
    if isinstance(v, str):
        return f"S({rust_str(v)})"
    raise TypeError(v)


def spec_code(s, looks) -> str:
    dynamic = s.choices is looks.CHOICES
    choices = "&[]" if dynamic else "&[" + ", ".join(choice(v) for v in s.choices) + "]"
    names = "&[]" if dynamic else "&[" + ", ".join(f"({choice(k)}, {rust_str(v)})" for k, v in s.names.items()) + "]"
    hints = "&[" + ", ".join(f"({choice(k)}, {rust_str(v)})" for k, v in s.hints.items()) + "]"
    impact = "&[" + ", ".join(f"({rust_str(k)}, {rust_str(v)})" for k, v in s.impact.items()) + "]"
    elsewhere = "&[" + ", ".join(f"({rust_str(k)}, {rust_str(v)})" for k, v in s.elsewhere.items()) + "]"
    sources = "&[" + ", ".join(rust_str(k) for k in s.sources) + "]"
    applies = ("None" if not s.applies else
               f"Some(({rust_str(s.applies[0])}, &[{', '.join(choice(v) for v in s.applies[1])}]))")
    return (
        "    Spec {\n"
        f"        key: {rust_str(s.key)},\n"
        f"        label: {rust_str(s.label)},\n"
        f"        choices: {choices},\n"
        f"        choices_are_list: {'true' if isinstance(s.choices, list) else 'false'},\n"
        f"        default: {choice(s.default)},\n"
        f"        names: {names},\n"
        f"        live: {'true' if s.live else 'false'},\n"
        f"        help: {rust_str(s.help)},\n"
        f"        saved: {'true' if s.saved else 'false'},\n"
        f"        group: {rust_str(s.group)},\n"
        f"        quick: {'true' if s.quick else 'false'},\n"
        f"        applies: {applies},\n"
        f"        later: {rust_str(s.later)},\n"
        f"        hints: {hints},\n"
        f"        impact: {impact},\n"
        f"        experimental: {'true' if s.experimental else 'false'},\n"
        f"        sources: {sources},\n"
        f"        elsewhere: {elsewhere},\n"
        f"        looks: {'true' if dynamic else 'false'},\n"
        "    },\n"
    )


def param_code(f) -> str:
    default = f"PDefault::Text({rust_str(f.default)})" if f.text else f"PDefault::Num({rust_float(f.default)})"
    int_range = isinstance(f.lo, int) and not isinstance(f.lo, bool)
    return (f"Param {{ key: {rust_str(f.key)}, label: {rust_str(f.label)}, lo: {rust_float(f.lo)}, "
            f"hi: {rust_float(f.hi)}, int_range: {'true' if int_range else 'false'}, default: {default}, "
            f"step: {rust_float(f.step)}, unit: {rust_str(f.unit)}, "
            f"names: &[{', '.join(rust_str(n) for n in f.names)}], text: {'true' if f.text else 'false'} }}")


def main() -> None:
    # The looks library reads its folder when framegen.looks is imported: point it at an empty one.
    os.environ["SMOOVPLAY_LOOKS_DIR"] = tempfile.mkdtemp(prefix="sp-codegen-")
    sys.path.insert(0, str(ROOT))
    from framegen import looks, settings

    out = [
        "// Generated by mac/core/tools/settings_codegen.py from framegen/settings.py and framegen/looks.py. Do not\n"
        "// edit: change the Python, then run the script again.\n\n"
        "use crate::looks::{NodeType, PDefault, Param};\n"
        "use crate::settings::C::{B, F, I, S};\n"
        "use crate::settings::Spec;\n\n",
        f"pub(crate) const IMPACT_PC: &str = {rust_str(settings.IMPACT_PC)};\n",
        "pub(crate) const CAPTURE_SIZES: &[(&str, (u32, u32))] = &["
        + ", ".join(f"({rust_str(k)}, ({w}, {h}))" for k, (w, h) in settings.CAPTURE_SIZES.items()) + "];\n\n",
        f"pub(crate) static SPECS: [Spec; {len(settings.SPECS)}] = [\n",
    ]
    out += [spec_code(s, looks) for s in settings.SPECS]
    out.append("];\n\n")
    out.append(f"pub(crate) const MIX: Param = {param_code(looks.MIX)};\n\n")
    out.append(f"pub(crate) static TYPES: [NodeType; {len(looks.TYPES_LIST)}] = [\n")
    for t in looks.TYPES_LIST:
        out.append(f"    NodeType {{ key: {rust_str(t.key)}, code: {t.code}, label: {rust_str(t.label)}, "
                   f"kind: {rust_str(t.kind)}, help: {rust_str(t.help)},\n        params: &[\n")
        for f in t.params:
            out.append(f"            {param_code(f)},\n")
        out.append("        ] },\n")
    out.append("];\n\n")
    out.append("/// The built-in looks, as normalize() leaves them: (id, name, [(type, on, [mix, settings...])]).\n")
    out.append("#[allow(clippy::type_complexity)]\npub(crate) static BUILTIN: &[(&str, &str, &[(&str, bool, &[f64])])] = &[\n")
    for key, look in looks.BUILTIN.items():
        nodes = []
        for n in look["nodes"]:
            t = looks.TYPES[n["type"]]
            assert not any(f.text for f in t.fields), "a built-in look with a LUT needs a text value here"
            vals = ", ".join(rust_float(n[f.key]) for f in t.fields)
            nodes.append(f"({rust_str(n['type'])}, {'true' if n['on'] else 'false'}, &[{vals}])")
        out.append(f"    ({rust_str(key)}, {rust_str(look['name'])}, &[\n        "
                   + ",\n        ".join(nodes) + "]),\n")
    out.append("];\n")
    out.append(f"pub(crate) const DEFAULT_LOOK: &str = {rust_str(looks.DEFAULT_LOOK)};\n")
    OUT.write_text("".join(out), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
